import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(path.join(root, 'apps/web/package.json'));
const sharp = require('sharp');
const master = await readFile(path.join(root, 'brand/ember-lens.svg'), 'utf8');
const markPath = master.match(/<path[^>]* d="([^"]+)"/)[1];
const orange = '#E95E00';
const dark = '#1F1A15';
const mark = (color) => `<path fill="${color}" fill-rule="evenodd" d="${markPath}"/>`;
const svg = (color) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img" aria-label="AI Film Camp">${mark(color)}</svg>\n`;
const tile = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" role="img" aria-label="AI Film Camp"><rect x="64" y="64" width="896" height="896" rx="200" fill="${dark}"/><svg x="176" y="176" width="672" height="672" viewBox="0 0 24 24" aria-hidden="true">${mark(orange)}</svg></svg>\n`;
const save = async (name, data) => {
  const dest = path.join(root, name);
  await mkdir(path.dirname(dest), { recursive: true });
  await writeFile(dest, data);
};
await save('apps/web/lib/brand.ts', `// Generated by pnpm brand:generate from brand/ember-lens.svg.\nexport const BRAND_MARK_PATH =\n  ${JSON.stringify(markPath)};\nexport const BRAND_ORANGE = "${orange}";\nexport const BRAND_DARK = "${dark}";\n`);
for (const [name, color] of [['logo-full-color',orange],['logo-mono-light','#FFFFFF'],['logo-mono-dark',dark]]) {
  await save(`apps/web/public/brand/${name}.svg`, svg(color));
}
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="2.8 1.5 18.4 20.5" role="img" aria-label="AI Film Camp">${mark(orange)}</svg>\n`;
await save('apps/web/app/icon.svg', favicon);
await save('apps/web/public/brand/app-icon.svg', tile);
const assets = 'apps/macos/AI Film Camp/Resources/Assets.xcassets';
await save(`${assets}/BrandMark.imageset/brand-mark.svg`, svg('#000000'));
await save(`${assets}/BrandMark.imageset/Contents.json`, JSON.stringify({
  images: [{ filename: 'brand-mark.svg', idiom: 'universal' }],
  info: { author: 'xcode', version: 1 },
  properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' }
}, null, 2) + '\n');
await save(`${assets}/BrandOrange.colorset/Contents.json`, JSON.stringify({
  colors: [{
    color: {
      'color-space': 'srgb',
      components: { red: '0.913725', green: '0.368627', blue: '0.000000', alpha: '1.000000' }
    },
    idiom: 'universal'
  }],
  info: { author: 'xcode', version: 1 }
}, null, 2) + '\n');
const iconSet = JSON.parse(await readFile(path.join(root, assets, 'AppIcon.appiconset/Contents.json'), 'utf8'));
for (const entry of iconSet.images) {
  const pixels = parseInt(entry.size) * parseInt(entry.scale);
  await save(`${assets}/AppIcon.appiconset/${entry.filename}`, await sharp(Buffer.from(tile), { density: 192 }).resize(pixels, pixels).png().toBuffer());
}
console.log('Generated web branding, macOS vector mark, and all 10 macOS app icon sizes.');
